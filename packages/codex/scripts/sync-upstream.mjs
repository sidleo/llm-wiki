/**
 * sync-upstream.mjs —— 同步共享 core 与 MCP 工具实现到 Codex 插件。
 *
 * Codex 插件通过本地 marketplace 安装后会复制到独立缓存目录，因此必须自包含：
 * - packages/core/ → packages/codex/vendor-core/
 * - packages/mcp/lib/{tools,format,instructions}.mjs → packages/codex/lib/
 *
 * config.mjs / core.mjs 是 Codex 适配层自己的薄封装，不覆盖。
 * 用法：node packages/codex/scripts/sync-upstream.mjs
 */

import { readdir, copyFile, mkdir, writeFile, readFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const codexRoot = join(here, '..')
const packagesRoot = join(codexRoot, '..')
const coreRoot = join(packagesRoot, 'core')
const mcpRoot = join(packagesRoot, 'mcp')
const vendor = join(codexRoot, 'vendor-core')
const lib = join(codexRoot, 'lib')

await mkdir(join(vendor, 'lib'), { recursive: true })
await mkdir(lib, { recursive: true })

await copyFile(join(coreRoot, 'index.mjs'), join(vendor, 'index.mjs'))
const coreFiles = (await readdir(join(coreRoot, 'lib'))).filter((f) => f.endsWith('.mjs'))
for (const f of coreFiles) {
  await copyFile(join(coreRoot, 'lib', f), join(vendor, 'lib', f))
}

const corePkg = JSON.parse(await readFile(join(coreRoot, 'package.json'), 'utf8'))
await writeFile(
  join(vendor, 'package.json'),
  JSON.stringify(
    {
      name: '@sidleo3/llm-wiki-core-vendor',
      version: corePkg.version,
      description: '@sidleo3/llm-wiki-core vendored into @sidleo3/codex-wiki (auto-generated by sync-upstream.mjs; do not edit)',
      type: 'module',
      main: 'index.mjs',
    },
    null,
    2,
  ) + '\n',
)

for (const f of ['tools.mjs', 'format.mjs', 'instructions.mjs']) {
  await copyFile(join(mcpRoot, 'lib', f), join(lib, f))
}

console.log(`codex vendor-core 已同步（${coreFiles.length} lib 文件 + index.mjs）；MCP 工具层已同步（3 个文件）`)
